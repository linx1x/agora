// Regenerates docs/DECISIONS-INDEX.md from docs/DECISIONS.md (one line per ADR).
// Run: pnpm adr:index   (also run it whenever you append an ADR)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

if (!existsSync('docs/DECISIONS.md')) {
  console.log('docs/DECISIONS.md not present (private notes); nothing to index');
  process.exit(0);
}

const src = readFileSync('docs/DECISIONS.md', 'utf8').split('\n');
const rows = [];
for (let i = 0; i < src.length; i++) {
  const m = /^## (ADR-\d+) — (.+)$/.exec(src[i]);
  if (!m) continue;
  let status = '';
  for (let j = i + 1; j < Math.min(i + 4, src.length); j++) {
    const s = /^Status:\s*([^.;(]*)/i.exec(src[j]);
    if (s) { status = s[1].trim(); break; }
  }
  rows.push(`- ${m[1]} — ${m[2]}${status ? ` [${status}]` : ''}`);
}
const out = `# Decision index

One line per ADR, generated by \`pnpm adr:index\` from docs/DECISIONS.md. Do not read DECISIONS.md in
full. Find the ADR you need here, then read just that entry:
\`grep -n -A14 '^## ADR-031' docs/DECISIONS.md\`. Append new ADRs to DECISIONS.md, then run \`pnpm adr:index\`.

${rows.join('\n')}
`;
writeFileSync('docs/DECISIONS-INDEX.md', out);
console.log(`${rows.length} ADRs indexed`);
